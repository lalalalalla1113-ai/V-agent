# Парсинг
# ===========================================================================

def _parse_variants(raw: str) -> list:
    if not raw:
        return ["Пустой ответ", "Пустой ответ"]
    raw = raw.strip()

    if "===ВАРИАНТ2===" in raw:
        parts = raw.split("===ВАРИАНТ2===")
        v1 = parts[0].replace("===ВАРИАНТ1===", "").strip()
        v2 = parts[1].strip() if len(parts) > 1 else ""
        if v1 and v2:
            return [_postprocess_variant(v1), _postprocess_variant(v2)]

    if "===ВАРИАНТ1===" in raw:
        v1 = raw.replace("===ВАРИАНТ1===", "").strip()
        return [_postprocess_variant(v1)]

    paragraphs = [p.strip() for p in raw.split("\n\n") if len(p.strip()) > 100]
    if len(paragraphs) >= 2:
        return [
            _postprocess_variant(paragraphs[0]),
            _postprocess_variant(paragraphs[1]),
        ]
    return [_postprocess_variant(raw)]


