def _build_prompt(idea, style, profile, hashtag_style="mixed",
                  samples=None, auto_add=True):
    parts = []

    parts.append(
        "Ты SMM-редактор. ЗАДАЧА: написать ДВА варианта поста для соцсетей.\n"
        "ВАЖНО: Не рассуждай. Сразу выдай готовый текст по формату ниже.\n\n"
        + HTML_FORMAT_RULES
    )

    if auto_add:
        parts.append(FACT_RULES_ON)
    else:
        parts.append(FACT_RULES_OFF)

    if profile:
        user_info = []
        if profile.name:
            user_info.append(f"Имя: {profile.name}")
        if profile.age:
            user_info.append(f"Возраст: {profile.age}")
        if profile.gender == "male":
            user_info.append("Пол: мужской")
        elif profile.gender == "female":
            user_info.append("Пол: женский")
        if profile.audience:
            user_info.append(f"Аудитория: {profile.audience}")
        if user_info:
            parts.append("О пользователе: " + ", ".join(user_info))

    if samples:
        clean_samples = [s for s in samples if s and s.strip()]
        if clean_samples:
            parts.append(
                "ПРИМЕРЫ ПОСТОВ ИЗ ЭТОГО КАНАЛА "
                "(ориентируйся на этот стиль, тон, длину, оформление, "
                "количество эмодзи, структуру):\n\n"
                + "\n\n— — —\n\n".join(clean_samples[:10])
            )

    style_prompt = STYLE_PROMPTS.get(
        style or "simple", STYLE_PROMPTS["simple"]
    )
    parts.append(style_prompt)

    parts.append(HTML_FORMAT_EXAMPLE)

    parts.append(
        "ФОРМАТ ОТВЕТА (ровно так, без слов перед первым маркером):\n\n"
        "===ВАРИАНТ1===\n"
        "<текст 500-900 символов>\n\n"
        "===ВАРИАНТ2===\n"
        "<второй вариант>\n\n"
        f"ИДЕЯ ПОСТА: {idea}\n\n"
        "НАЧНИ ОТВЕТ СИМВОЛАМИ «===ВАРИАНТ1===»."
    )
    return "\n\n".join(parts)


