def generate_content(idea, style, history=None, profile=None,
                     hashtag_style="mixed", samples=None, auto_add=True):
    """Генерирует 2 варианта поста.

    samples — список примеров постов канала.
    auto_add — True: ИИ может добавлять общеизвестные факты;
               False: пишет строго по теме, просит 2+ факта.
    """
    ok, hits = bad_words.check_text(idea)
    if not ok:
        return [bad_words.forbidden_message(hits)]

    full_prompt = _build_prompt(idea, style, profile, hashtag_style,
                                samples, auto_add)

    result = cf_text.ask(
        full_prompt,
        system="Ты SMM-редактор. Выдаёшь только готовый текст.",
        max_tokens=1500,
    )
    if not result:
        return ["❌ Не удалось сгенерировать текст.",
                "Попробуй ещё раз через минуту."]
    return _parse_variants(result)


def generate_hashtags(topic, style="simple", hashtag_style="mixed", count=10):
    """Генерирует хештеги одной строкой через пробел."""
    ok, hits = bad_words.check_text(topic)
    if not ok:
        return bad_words.forbidden_message(hits)

    hashtag_prompt = HASHTAG_STYLES.get(hashtag_style, HASHTAG_STYLES["mixed"])

    prompt = (
        f"Придумай {count} хештегов для поста на тему «{topic}».\n"
        f"Стратегия: {hashtag_prompt}\n"
        f"Выведи ОДНОЙ строкой через пробел. Без переносов. "
        f"Только хештеги, без слов."
    )

    result = cf_text.ask(prompt, max_tokens=300)
    if result:
        tags = re.findall(r"#[\wа-яё]+", result, re.IGNORECASE)
        if tags and len(tags) >= 3:
            return " ".join(tags[:count])

    words = [w.lower() for w in topic.split() if w.isalpha()][:5]
    return " ".join([f"#{w}" for w in words] + ["#контент", "#идеи",
                                                 "#блог", "#пост"])